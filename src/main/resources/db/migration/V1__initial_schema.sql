CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) UNIQUE,
    nome varchar(255),
    senha varchar(255),
    telegram_link_expires_at timestamptz(6),
    telegram_link_token_hash varchar(255),
    telegram_user_id bigint UNIQUE
);

CREATE TABLE categorias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meta_mensal numeric(19, 2),
    nome varchar(255) NOT NULL,
    tipo varchar(255) CHECK (tipo IN ('RECEITA', 'DESPESA')),
    user_id bigint REFERENCES users(id)
);

CREATE TABLE transacoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data date,
    descricao varchar(255),
    tipo smallint CHECK (tipo BETWEEN 0 AND 1),
    valor numeric(19, 2),
    categoria_id bigint REFERENCES categorias(id),
    user_id bigint REFERENCES users(id)
);

CREATE TABLE telegram_transacoes_pendentes (
    id varchar(255) PRIMARY KEY,
    categoria_id bigint,
    categoria_nome varchar(255),
    data date,
    descricao varchar(255),
    expira_em timestamptz(6),
    telegram_user_id bigint,
    tipo varchar(255) CHECK (tipo IN ('RECEITA', 'DESPESA')),
    valor numeric(19, 2)
);
